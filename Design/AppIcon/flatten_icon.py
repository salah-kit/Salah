#!/usr/bin/env python3
"""Write the flat vector app icon that the iOS welcome screen draws.

Run from anywhere with Python 3.9 or later; it needs no packages:

    python3 Design/AppIcon/flatten_icon.py          # write the SVGs
    python3 Design/AppIcon/flatten_icon.py --check  # exit 1 if they're out of date

The system draws the app icon itself, from Salah.icon, everywhere but inside the app. iOS has no
API that hands the app its own icon, so the welcome screen draws this copy instead. It stacks the
layer SVGs of Salah.icon back to front with each layer's opacity, once for the light appearance
and once for the dark one, into the OnboardingIcon image set. Liquid Glass and the icon's mask come
only from the system, so the copy is flat and the view clips its corners.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ICON = HERE / 'Salah.icon'
OUTPUT = HERE.parent.parent / 'SalahIOS' / 'Assets.xcassets' / 'OnboardingIcon.imageset'
APPEARANCES = {'light': None, 'dark': 'dark'}
SVG = re.compile(r'^\s*<svg\b[^>]*>(.*)</svg>\s*$', re.S)
# What the flat copy reproduces. Groups' shadow, translucency and specular are Liquid Glass, which
# only the system draws. Anything else in icon.json would change the icon without changing the
# copy, so it stops the script instead of passing --check.
LAYER_KEYS = {'name', 'glass'} | {
    f'{key}{suffix}' for key in ('image-name', 'opacity', 'hidden', 'fill') for suffix in ('', '-specializations')
}
GROUP_KEYS = {'name', 'layers', 'shadow', 'translucency', 'specular'}
UNSUPPORTED_SVG = re.compile(r'href=|url\([\'"]|\bid=\'')


def specialized(layer, key, appearance, default):
    """The layer's value for an appearance, falling back to the unspecialized value."""
    if key in layer:
        return layer[key]
    values = {item.get('appearance'): item['value'] for item in layer.get(f'{key}-specializations', [])}
    return values.get(appearance, values.get(None, default))


def layer_body(name, prefix):
    """The contents of a layer SVG, with its ids prefixed so layers can share one document."""
    match = SVG.match((ICON / 'Assets' / name).read_text())
    if not match:
        sys.exit(f'{name} is not a single <svg> element.')
    if UNSUPPORTED_SVG.search(match.group(1)):
        sys.exit(f'{name} uses href or a quoted id or url(), which the flat copy can\'t prefix.')
    body = re.sub(r'\bid="([^"]+)"', rf'id="{prefix}-\1"', match.group(1))
    return re.sub(r'url\(#([^)]+)\)', rf'url(#{prefix}-\1)', body).strip()


def flatten(appearance):
    document = json.loads((ICON / 'icon.json').read_text())
    # icon.json lists groups, and the layers in each group, front to back.
    layers = [layer for group in reversed(document['groups']) for layer in reversed(group['layers'])]
    for group in document['groups']:
        unsupported = set(group) - GROUP_KEYS
        unsupported |= {f'{layer["name"]}: {key}' for layer in group['layers'] for key in set(layer) - LAYER_KEYS}
        if unsupported:
            sys.exit(f'The flat copy can\'t reproduce {group["name"]} ({", ".join(sorted(unsupported))}).')
    parts = []
    for layer in layers:
        if specialized(layer, 'fill', appearance, 'automatic') != 'automatic':
            sys.exit(f'The flat copy can\'t reproduce the {appearance or "light"} fill of {layer["name"]}.')
        if specialized(layer, 'hidden', appearance, False):
            continue
        name = specialized(layer, 'image-name', appearance, None)
        prefix = re.sub(r'[^a-z0-9]+', '-', layer['name'].lower()).strip('-')
        opacity = specialized(layer, 'opacity', appearance, 1.0)
        attributes = f' id="{prefix}"' + (f' opacity="{opacity:g}"' if opacity != 1 else '')
        parts.append(f'<g{attributes}>\n{layer_body(name, prefix)}\n</g>')
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
        f'<!-- Generated by Design/AppIcon/flatten_icon.py from Salah.icon. Don\'t edit. -->\n'
        + '\n'.join(parts)
        + '\n</svg>\n'
    )


def main():
    check = sys.argv[1:] == ['--check']
    stale = []
    for suffix, appearance in APPEARANCES.items():
        path = OUTPUT / f'icon-{suffix}.svg'
        svg = flatten(appearance)
        if check:
            if not path.exists() or path.read_text() != svg:
                stale.append(path.name)
        else:
            path.write_text(svg)
    if stale:
        sys.exit(f'Out of date: {", ".join(stale)}. Run python3 Design/AppIcon/flatten_icon.py.')
    print('The flat app icon matches Salah.icon.' if check else f'Wrote the flat app icon to {OUTPUT}.')


if __name__ == '__main__':
    main()
